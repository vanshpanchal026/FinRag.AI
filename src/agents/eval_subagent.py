"""Two-Tier Evaluation Sub-Agent module for FinRAG-Eval.

Implements zero-hallucination verification:
- Tier 1: Deterministic Regex numerical consistency check comparing answer numbers
  verbatim against concatenated raw chunks (normalized for commas).
- Tier 2: LLM-as-a-Judge audit (using llama-3.1-8b-instant) scoring faithfulness,
  citation accuracy, and answer relevance.
- Output: Strict JSON schema matching docs/DesignDocument.md Section 3B.

Sources:
- docs/DetectionLogic.md Section 3 & 4
- docs/DesignDocument.md Section 3B & 4.2
"""

import re
import uuid
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from src.agents.llm_client import LLMClient
from src.agents.math_ast_verifier import (
    clean_indian_number,
    extract_raw_numbers,
    check_derived_arithmetic,
    verify_unit_equivalence,
)
from src.config import settings

# Exact System Prompt from docs/DetectionLogic.md Section 4
EVAL_SYSTEM_PROMPT = """You are a strict Financial Compliance & RAG Evaluation Auditor.
You will receive: 

1. USER_QUERY
2. RETRIEVED_CHUNKS (with Chunk IDs and Page Numbers)
3. GENERATED_ANSWER
4. DETERMINISTIC_NUMERIC_REPORT (List of verified and unverified numbers)

Evaluate the GENERATED_ANSWER strictly across three criteria on a scale of 0 to 10: 

* faithfulness_score (0-10): Are all claims, reasons, and numbers 100% grounded in RETRIEVED_CHUNKS? Deduct 5 points immediately for any hallucinated number or fabricated management statement.
* citation_accuracy_score (0-10): Do the [Source: File | Page: X | Chunk: Y] tags accurately point to the specific chunk containing that fact?
* answer_relevance_score (0-10): Did the answer directly and completely address all parts of the USER_QUERY?

Return ONLY a valid JSON object matching this exact schema:
{
"faithfulness_score": int,
"citation_accuracy_score": int,
"answer_relevance_score": int,
"hallucination_flag": bool,
"unverified_claims": ["list of any unsupported statements or numbers"],
"audit_reasoning": "1-2 crisp sentences explaining the scores."
}"""

# Section 3.1 Numerical Extractor Pattern
NUMERICAL_PATTERN = re.compile(
    r"(?<![a-zA-Z0-9_])\d+(?:,\d+)*(?:\.\d+)?%?(?![a-zA-Z0-9_])"
)

# Inline Citation Pattern for exclusion filter
CITATION_STRIP_PATTERN = re.compile(r"\[Source:\s*[^\]]+\]", re.IGNORECASE)


class DeterministicReport(BaseModel):
    """Tier-1 Deterministic check results with AST math and unit verification."""

    numbers_in_answer: List[str] = Field(default_factory=list)
    verbatim_matches: List[str] = Field(default_factory=list)
    unit_converted_matches: List[Dict[str, Any]] = Field(default_factory=list)
    ast_math_traces: List[Dict[str, Any]] = Field(default_factory=list)
    unverified_numbers: List[str] = Field(default_factory=list)
    numeric_match_pass: bool = True


class LLMJudgeScores(BaseModel):
    """Tier-2 LLM Judge evaluation scores."""

    faithfulness_score: int = Field(default=10, ge=0, le=10)
    citation_accuracy_score: int = Field(default=10, ge=0, le=10)
    answer_relevance_score: int = Field(default=10, ge=0, le=10)
    reasoning: str = Field(default="All figures and claims grounded in retrieved context.")


class EvalReport(BaseModel):
    """Full Eval Sub-Agent Output Schema conforming to docs/DesignDocument.md Section 3B."""

    query_id: str
    deterministic_checks: DeterministicReport
    llm_judge_scores: LLMJudgeScores
    hallucination_flag: bool = False


def run_deterministic_tier1_check(
    generated_answer: str,
    golden_chunks: List[Dict[str, Any]],
) -> Dict[str, Any]:
    """Execute Tier-1 Zero-Latency Deterministic numerical check.

    Combines:
    1. Verbatim string matching against chunk texts (comma-normalized).
    2. Unit equivalence normalization (Lakhs vs Crores vs Millions vs Billions).
    3. Python AST arithmetic derivation verification (YoY %, QoQ %, bps margin compression, differences).

    Args:
        generated_answer: Response generated by AnalystAgent.
        golden_chunks: Retrieved Golden Chunks provided as context.

    Returns:
        Dictionary conforming to DeterministicReport schema.
    """
    if not generated_answer:
        return {
            "numbers_in_answer": [],
            "verbatim_matches": [],
            "unit_converted_matches": [],
            "ast_math_traces": [],
            "unverified_numbers": [],
            "numeric_match_pass": True,
        }

    # Step 1: Strip citations to prevent page/chunk numbers from triggering false positives
    answer_clean = CITATION_STRIP_PATTERN.sub("", generated_answer)

    # Step 2: Extract all numerical tokens from answer
    extracted_nums = NUMERICAL_PATTERN.findall(answer_clean)

    # Step 3: Build concatenated raw corpus with comma normalization
    corpus_chunks_text = " ".join([c.get("text", "") for c in golden_chunks])
    normalized_corpus = corpus_chunks_text.replace(",", "")
    corpus_numbers = extract_raw_numbers(corpus_chunks_text)

    # Step 4: Verify each number
    verbatim_matches: List[str] = []
    unit_converted_matches: List[Dict[str, Any]] = []
    ast_math_traces: List[Dict[str, Any]] = []
    unverified_nums: List[str] = []

    for num in extracted_nums:
        norm_num = num.replace(",", "")

        # A. Check Verbatim with strict numerical boundaries (prevent '500' matching inside '50000')
        boundary_pattern = rf"(?<![0-9])(?<!\d\.){re.escape(norm_num)}(?![0-9]|\.\d)"
        is_verbatim = bool(re.search(boundary_pattern, normalized_corpus))

        if is_verbatim:
            verbatim_matches.append(num)
            continue

        # B. Check Unit Equivalence (Lakhs vs Crores)
        unit_trace = verify_unit_equivalence(
            claimed_token=num,
            answer_context=answer_clean,
            raw_chunks_text=corpus_chunks_text,
        )
        if unit_trace and unit_trace.is_match:
            unit_converted_matches.append(unit_trace.model_dump())
            continue

        # C. Check Derived AST Arithmetic (YoY %, bps margin compression, differences)
        # Find sentence context for this number without splitting decimal floats
        sentence_context = ""
        for sentence in re.split(r"(?<=[a-zA-Z0-9%])\.\s+", answer_clean):
            if num in sentence:
                sentence_context = sentence
                break

        math_trace = check_derived_arithmetic(
            claimed_num_str=num,
            corpus_numbers=corpus_numbers,
            context_sentence=sentence_context,
        )
        if math_trace and math_trace.is_valid:
            ast_math_traces.append(math_trace.model_dump())
            continue

        # If none passed, flag as unverified
        unverified_nums.append(num)

    # Step 5: Verdict
    numeric_match_pass = len(unverified_nums) == 0

    return {
        "numbers_in_answer": extracted_nums,
        "verbatim_matches": verbatim_matches,
        "unit_converted_matches": unit_converted_matches,
        "ast_math_traces": ast_math_traces,
        "unverified_numbers": unverified_nums,
        "numeric_match_pass": numeric_match_pass,
    }


class EvalSubAgent:
    """Evaluation Sub-Agent executing Tier-1 Regex check and Tier-2 LLM Judge audit."""

    def __init__(
        self,
        llm_client: Optional[LLMClient] = None,
        model: Optional[str] = None,
        system_prompt: str = EVAL_SYSTEM_PROMPT,
    ):
        self.llm_client = llm_client or LLMClient()
        self.model = model or settings.eval_agent_model
        self.system_prompt = system_prompt

    def evaluate(
        self,
        user_query: str,
        golden_chunks: List[Dict[str, Any]],
        generated_answer: str,
        query_id: Optional[str] = None,
        skip_llm_judge: bool = False,
    ) -> Dict[str, Any]:
        """Perform end-to-end evaluation returning full audit scorecard.

        Args:
            user_query: User's original query.
            golden_chunks: Chunks passed to analyst agent.
            generated_answer: Answer text generated by analyst agent.
            query_id: Optional tracking identifier.
            skip_llm_judge: If True, uses deterministic fallback for Tier-2.

        Returns:
            Dictionary matching EvalReport schema.
        """
        qid = query_id or str(uuid.uuid4())

        # 1. Tier-1 Deterministic Check
        tier1_report = run_deterministic_tier1_check(
            generated_answer=generated_answer,
            golden_chunks=golden_chunks,
        )

        # 2. Tier-2 LLM-as-a-Judge Check
        llm_scores: Dict[str, Any] = {}
        hallucination_flag = not tier1_report["numeric_match_pass"]

        if skip_llm_judge:
            # Deterministic heuristic scoring
            if tier1_report["numeric_match_pass"]:
                llm_scores = {
                    "faithfulness_score": 10,
                    "citation_accuracy_score": 10,
                    "answer_relevance_score": 9,
                    "reasoning": "All extracted numerical figures match verbatim in source chunks.",
                }
            else:
                llm_scores = {
                    "faithfulness_score": 3,
                    "citation_accuracy_score": 5,
                    "answer_relevance_score": 7,
                    "reasoning": f"Unverified numbers found: {tier1_report['unverified_numbers']}",
                }
        else:
            try:
                # Format chunks for auditor
                chunks_summary = []
                for c in golden_chunks:
                    cid = c.get("chunk_id", "")
                    pno = c.get("metadata", {}).get("page_no", 1)
                    sfile = c.get("metadata", {}).get("source_file", "")
                    chunks_summary.append(
                        f"Chunk ID: {cid} | File: {sfile} | Page: {pno}\nText: {c.get('text', '')}"
                    )
                chunks_text = "\n---\n".join(chunks_summary)

                judge_prompt = (
                    f"USER_QUERY:\n{user_query}\n\n"
                    f"RETRIEVED_CHUNKS:\n{chunks_text}\n\n"
                    f"GENERATED_ANSWER:\n{generated_answer}\n\n"
                    f"DETERMINISTIC_NUMERIC_REPORT:\n{tier1_report}\n\n"
                    f"Evaluate the answer strictly based on the three criteria."
                )

                messages = [
                    {"role": "system", "content": self.system_prompt},
                    {"role": "user", "content": judge_prompt},
                ]

                raw_judge_output = self.llm_client.generate_json(
                    messages=messages,
                    model=self.model,
                )

                faithfulness = int(raw_judge_output.get("faithfulness_score", 10))
                citation_acc = int(raw_judge_output.get("citation_accuracy_score", 10))
                relevance = int(raw_judge_output.get("answer_relevance_score", 10))
                judge_flag = bool(raw_judge_output.get("hallucination_flag", False))
                reasoning = str(
                    raw_judge_output.get("audit_reasoning")
                    or raw_judge_output.get("reasoning")
                    or "Audit completed."
                )

                hallucination_flag = (
                    judge_flag
                    or not tier1_report["numeric_match_pass"]
                    or faithfulness < 7
                )

                llm_scores = {
                    "faithfulness_score": faithfulness,
                    "citation_accuracy_score": citation_acc,
                    "answer_relevance_score": relevance,
                    "reasoning": reasoning,
                }
            except Exception as e:
                # Fallback to Tier-1 grounded inference if LLM endpoint unreachable
                if tier1_report["numeric_match_pass"]:
                    llm_scores = {
                        "faithfulness_score": 10,
                        "citation_accuracy_score": 10,
                        "answer_relevance_score": 9,
                        "reasoning": f"Tier-1 verification passed (LLM judge offline: {e}).",
                    }
                else:
                    llm_scores = {
                        "faithfulness_score": 4,
                        "citation_accuracy_score": 6,
                        "answer_relevance_score": 7,
                        "reasoning": f"Unverified numbers detected in answer: {tier1_report['unverified_numbers']}.",
                    }

        report = EvalReport(
            query_id=qid,
            deterministic_checks=DeterministicReport(**tier1_report),
            llm_judge_scores=LLMJudgeScores(**llm_scores),
            hallucination_flag=hallucination_flag,
        )

        return report.model_dump()
